function detectLocale() {
  try {
    const saved = localStorage.getItem(storageKey);
    if (saved === 'es' || saved === 'en') return saved;
  } catch { /* Storage may be disabled. */ }
  return typeof navigator !== 'undefined' && /^en(?:-|$)/i.test(navigator.language || '') ? 'en' : 'es';
}

let locale = detectLocale();
const listeners = new Set();
const placeholderPattern = /\{\{\s*([\w]+)\s*\}\}/g;
const exactSpanishKeys = new Map();
const spanishTemplates = [];

for (const [key, template] of Object.entries(messages.es)) {
  if (template.includes('{{')) {
    const names = [];
    let index = 0;
    let pattern = '^';
    for (const match of template.matchAll(placeholderPattern)) {
      pattern += template.slice(index, match.index).replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
      pattern += '(.+?)';
      names.push(match[1]);
      index = match.index + match[0].length;
    }
    pattern += template.slice(index).replace(/[.*+?^${}()|[\]\\]/g, '\\$&') + '$';
    spanishTemplates.push({ key, names, pattern: new RegExp(pattern) });
  } else if (!exactSpanishKeys.has(template)) {
    exactSpanishKeys.set(template, key);
  }
}

function substitute(template, values) {
  return template.replace(placeholderPattern, (match, key) => Object.hasOwn(values, key) ? String(values[key]) : match);
}

function translateError(source) {
  if (errorTextKeys.has(source)) return messages.en[errorTextKeys.get(source)];
  let match = source.match(/^Faltan los parámetros de «(.+)»\.$/);
  if (match) return substitute(messages.en['error.missingParameters'], { piece: match[1] });
  match = source.match(/^La operación depende de una pieza inexistente: (.+)\.$/);
  if (match) return `${messages.en['error.operationDependency']} ${match[1]}.`;
  match = source.match(/^El perfil debe contener entre (\d+) y (\d+) puntos\.$/);
  if (match) return substitute(messages.en['error.profilePointCount'], { min: match[1], max: match[2] });
  match = source.match(/^El perfil supera la dimensión máxima de ([\d.]+) mm\.$/);
  if (match) return substitute(messages.en['error.profileDimension'], { max: match[1] });
  match = source.match(/^El proyecto puede contener hasta (\d+) operaciones\.$/);
  if (match) return substitute(messages.en['error.projectLimit'], { max: match[1] });
  match = source.match(/^El identificador «(.+)» está duplicado\.$/);
  if (match) return `${messages.en['error.duplicateId']} (${match[1]}).`;
  match = source.match(/^Faltan los parámetros de «(.+)»\.$/);
  if (match) return substitute(messages.en['error.missingParameters'], { piece: match[1] });
  match = source.match(/^«(.+)» debe referenciar una pieza anterior existente\.$/);
  if (match) return substitute(messages.en['error.objectReference'], { piece: match[1] });
  match = source.match(/^«(.+)»: (.+)$/);
  if (match) return substitute(messages.en['error.featureFailure'], { piece: match[1], detail: translateError(match[2]) });
  return source;
}

export function t(key, values = {}) {
  let template = messages[locale][key] ?? messages.es[key];
  if (!template && locale === 'en') {
    const exactKey = exactSpanishKeys.get(key);
    if (exactKey) template = messages.en[exactKey];
    if (!template) {
      for (const entry of spanishTemplates) {
        const match = key.match(entry.pattern);
        if (!match) continue;
        const params = Object.fromEntries(entry.names.map((name, index) => [name, match[index + 1]]));
        if (Object.hasOwn(params, 'label')) {
          const labelKey = exactSpanishKeys.get(params.label);
          if (labelKey) params.label = messages.en[labelKey];
        }
        template = substitute(messages.en[entry.key], params);
        break;
      }
    }
    if (!template) template = translateError(key);
  }
  if (!template) template = key;
  return substitute(template, values);
}

export function getLocale() { return locale; }
export function localeTag() { return locale === 'en' ? 'en-US' : 'es-MX'; }
export function formatNumber(value, options) { return Number(value).toLocaleString(localeTag(), options); }

export function applyStaticTranslations(root = document) {
  const elements = root.querySelectorAll('[data-i18n], [data-i18n-title], [data-i18n-aria], [data-i18n-placeholder], [data-i18n-content]');
  for (const element of elements) {
    if (element.dataset.i18n) element.textContent = t(element.dataset.i18n);
    if (element.dataset.i18nTitle) element.title = t(element.dataset.i18nTitle);
    if (element.dataset.i18nAria) element.setAttribute('aria-label', t(element.dataset.i18nAria));
    if (element.dataset.i18nPlaceholder) element.setAttribute('placeholder', t(element.dataset.i18nPlaceholder));
    if (element.dataset.i18nContent) element.setAttribute('content', t(element.dataset.i18nContent));
  }
  const title = root.querySelector('title[data-i18n]');
  if (title) document.title = title.textContent;
}

export function onLocaleChange(listener) {
  listeners.add(listener);
  return () => listeners.delete(listener);
}

export function setLocale(next, { persist = true } = {}) {
  if (next !== 'es' && next !== 'en') return false;
  if (next === locale) return true;
  locale = next;
  if (persist) {
    try { localStorage.setItem(storageKey, locale); } catch { /* Language remains active for this tab. */ }
  }
  if (typeof document !== 'undefined') {
    document.documentElement.lang = locale;
    applyStaticTranslations(document);
  }
  for (const listener of listeners) listener(locale);
  return true;
}

if (typeof document !== 'undefined') {
  document.documentElement.lang = locale;
  applyStaticTranslations(document);
  const selector = document.querySelector('#locale-select');
  if (selector) {
    selector.value = locale;
    selector.addEventListener('change', () => setLocale(selector.value));
  }
}
